/**
 * 合规豁免标记词。禁词命中后,若命中位置**之前**的同行上下文出现下列任一标记,判定为合规。
 *
 * 为什么不用"豁免短语白名单":2026-08-01 实测三端 src 中 `平台内?投递` 命中 33 处,
 * 其中 30 处合规,前缀有 24 种不同写法(「去来源平台投递」「不参与平台内投递」「无平台内投递」
 * 「跳转外部平台投递」「扫码前往来源平台投递」…)。逐字白名单永远补不齐,且漏一个就误报一个页面。
 * 改为按语义标记判定:**否定式边界声明**与**指向站外来源**这两类才是合法用法。
 *
 * NEGATED —— 否定式边界声明(声明"我们不做"),**必须是多字短语**。
 * 一律不收单字标记(「不」「无」「非」):它们太容易被营销句式白拿豁免。
 * 实测反例:单字「无」会让「无需注册,一键投递到企业」「无门槛投递简历」全部误判为合规,
 * 单字「非」会让「非常快,立即投递」误判为合规 —— 这类漏放比误报危险得多。
 *
 * OUTBOUND —— 指向第三方 / 官方来源平台的站外引导,是合规白名单文案本身。
 *
 * 以上两类按**前向回看窗口**判定(见 COMPLIANCE_EXEMPTION_LOOKBEHIND)。
 */
