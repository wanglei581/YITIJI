/**
 * 底栏「问小青」带去顾问页的草稿（审查意见 B1）。
 *
 * 按钮上写「问小青：扫描件接下来呢」；顾问页输入框里放的是一句不带前缀的自然问句，
 * 再加一句请她只说明这一步该怎么做、不替用户下结论（AI 只解释、建议，不替人做决定）。
 * 此前 draft 与 label 同一句，用户点过去，输入框里是「问小青：扫描件接下来呢」——把按钮名带进了对话框。
 * 只填输入框、不自动发送；现场无人值守，草稿里不写「工作人员」「联系」。
 */
export function askDraftOf(label: string): string {
  const question = label.replace(/^问小青[：:]\s*/, '').replace(/[？?]\s*$/, '').trim()
  return `${question}？请只说明这一步该怎么做，不要替我下结论。`
}
