// ============================================================
// 小青被问到设备故障时的固定回答（真机实操 F-04，2026-10-10）
//
// 起因：在一体机上问「打印机卡纸怎么办」，模型教人自己打开前盖和纸盒抽纸。
// 现场无人值守，用户自己拆机可能受伤、也可能把机器弄坏，所以这一类不靠模型自觉：
// 按关键词判成「设备故障」，直接回下面这段固定的话，不送模型（模型连不上也照样能答）。
//
// 固定回答只说核实过的事，下面几样是有意不写的：
//   - 「我们已经收到提醒」「会尽快处理」：提醒送不送得到人，取决于告警推送配没配、
//     终端在不在运行状态，这段无条件显示的话不能这么说。
//   - 电话号码：只指到帮助中心（那一页按后台配置显示服务电话，没配就指到《隐私政策》
//     里的联系方式），所以这里不存在编一个号码的问题。小程序帮助页没有电话，指到意见反馈。
//   - 「换一台机器」：这里不知道附近有没有别的在线终端。
//   - 找现场的人：现场无人值守。
//
// 判定宁可多拦：漏拦的后果是模型教人拆机，多拦的后果只是用户换个问法。放过的只有三类：
//   - 在说求职内容（把修打印机的经历写进简历、岗位要求里提到卡纸、面试官会问）；
//   - 找维修这一行的工作（「想找设备维修的工作」里的「维修」不是要修眼前这台）；
//   - 自带键盘打不出某个字、电话打不了（也说「打不出来」「打不了」，但不是打印机的事）。
// 改这两段话或判定范围之前，先过产品负责人与合规。
// ============================================================

export type DeviceFaultChannel = 'kiosk' | 'miniapp'

const KIOSK_REPLY =
  '机器卡纸、缺纸、打不出来或有其它故障时，请不要自己打开机器、拉扯纸张、按机身上的按键或拔插电源。' +
  '机器暂时用不了的话，请稍后再来；需要帮助请看「帮助中心」里的联系方式。' +
  '如果看到冒烟、闻到焦味或听到异常响声，请立刻离开机器；有明火或人身危险请拨打 119。'

const MINIAPP_REPLY =
  '一体机卡纸、缺纸、打不出来或有其它故障时，请不要自己打开机器、拉扯纸张、按机身上的按键或拔插电源。' +
  '机器暂时用不了的话，请稍后再来；需要帮助可以在「意见反馈」里告诉我们。' +
  '如果看到冒烟、闻到焦味或听到异常响声，请立刻离开机器；有明火或人身危险请拨打 119。'

/**
 * 写给模型的约束，字由合规定（2026-10-10）。关键词兜不住所有问法；语音小青的话不经过后端，
 * 关键词拦不到，只有这一句管着。加在小青文字、语音共用的系统约束和作业面问答的提示词里。
 */
export const DEVICE_FAULT_PROMPT_RULE =
  '设备故障：用户问到打印机或本机卡纸、缺纸、打不出来、损坏、冒烟、异响等故障时，不要教用户打开机器、取纸、按机身按键或拔插电源，' +
  '也不要说已经有人收到提醒或会来处理；不要自己说出任何电话号码，不要提退款或订单状态。' +
  '只提醒不要自行处理、可以稍后再来，并请用户查看帮助页上的联系方式；说到冒烟、焦味或明火时，先提醒离开机器，有明火或人身危险拨打 119。'

export function deviceFaultReply(channel: DeviceFaultChannel): string {
  return channel === 'miniapp' ? MINIAPP_REPLY : KIOSK_REPLY
}

/** 一体机带咨询主题时会在原话前加这一段，判定只看用户自己那一句。 */
const TOPIC_PREFIX = /^当前咨询主题：[^\n]*\n用户问题：/

/** 比这更长的多半是贴进来的岗位要求、经历或文稿，不是「机器坏了」的求助。 */
const MAX_FAULT_QUESTION_CHARS = 160

// 「机器」排除机器学习、机器人这类求职里常见的词；「设备」只认「这个设备」「这设备」，
// 单说「设备」多半是设备工程师、设备管理这类岗位名。
const DEVICE = '(?:打印机|复印机|扫描仪|一体机|机器(?!学习|人|视觉|翻译)|机子|这台|本机|这个?设备)'
// 同一句以内。逗号不算句子的边界：「打印机不知道怎么了，没反应」要能连起来看。
const SAME_CLAUSE = '[^。！？!?；;]'
const TAKE_OUT = '(?:拽|拉|抽|扯|取|拿|弄)'
const HOW_TO = '(?:怎么|如何|咋|怎样|帮我|我来|我想|能不能|可以)'

/** 故障征兆，以及想自己开盖、重启、断电。 */
const SYMPTOM_PATTERNS: readonly RegExp[] = [
  // 卡纸
  new RegExp(
    `卡纸|夹纸|塞纸|纸(?!质)${SAME_CLAUSE}{0,4}(?:卡|塞)(?:住|在|死|了|里|进|着)|卡(?:住|着|了)(?:的|一张|张)?纸|卡在(?:里面|里边|里头|机器|打印机|纸盒|出纸口)` +
    `|纸${SAME_CLAUSE}{0,6}${TAKE_OUT}不出|(?:把|将)纸(?!质)${SAME_CLAUSE}{0,3}${TAKE_OUT}出来` +
    `|纸(?!质)${SAME_CLAUSE}{0,3}(?:出不来|不出来|没出来|打歪|歪了|皱了|是皱的|撕破|破了|烂了)|出纸口${SAME_CLAUSE}{0,6}(?:没|不|卡|堵)`,
  ),
  // 缺纸、耗材（「没粉丝」「换粉色底」不是说碳粉）
  /缺纸|没有?纸(?!质)|无纸(?!化|质)|纸张?都?(?:用|打)?(?:完|光|没)了|(?:加|补|装|添)纸|缺粉|缺墨|没有?墨(?!迹)|没有?碳粉|没有?粉了|(?:加|换|补|添)(?:墨|碳粉)|(?:加|换)粉(?!色|红|底)|硒鼓|墨盒|粉盒|碳粉|墨粉/,
  // 打印不出来（「能不能打印身份证」里的「不能打印」是在问规定，「打印不动产证明」是要打的东西，都不算）
  /印不出|打印不了|(?:无法|没法|没办法)打印|(?<!能)不能打印(?:了|怎么办|咋办|$)|[不没]出纸|出不来纸|出不了纸|[不没]吐纸|吐不出|没打出来|没印出来|打印(?:失败|出错|报错|异常|中断|卡住|没反应|不动(?!产))/,
  new RegExp(`(?:打|印)(?:到|了)一半${SAME_CLAUSE}{0,6}(?:不动(?!产)|停|卡|没反应|没了|不出|断)|(?:打|印|点|按)了${SAME_CLAUSE}{0,4}没(?:反应|动静)`),
  // 打出来的纸明显不对（模糊、偏淡、版面留白多可能是文件本身的事，不算）
  new RegExp(`(?:打印?|印)(?:出来|有)${SAME_CLAUSE}{0,6}(?:白纸|空白页|空白的|全黑|黑线|黑条|白条|条纹|重影|掉粉|漏粉)`),
  // 机器坏了
  new RegExp(
    `${DEVICE}${SAME_CLAUSE}{0,10}(?:坏了|坏掉|坏啦|故障|出问题|有点?问题(?!想|要|请|问|咨询)|没反应|不工作|不动(?!产)|死机|卡死|卡住了|卡了|用不了|不能用了|没法用|无法使用|` +
    `开不了机|开不开|不开机|黑屏|蓝屏|花屏|白屏|报错|异常|失灵|罢工|离线|脱机|掉线|发烫|很烫|烫手|过热|一直响|响个不停|很响|噪音|声音(?:好|很|太|特别|有点|这么)大|` +
    `(?:拍|踢|敲|砸|晃|摇)它?(?:一|两|几)?(?:下|脚))`,
  ),
  new RegExp(`(?:踢|敲|砸|晃|摇)${SAME_CLAUSE}{0,3}${DEVICE}|连不上${SAME_CLAUSE}{0,3}${DEVICE}|(?<![盘机脑件历片])(?:是不是|好像|可能|估计)坏了|坏了吧|(?:破|烂|垃圾)(?:机器|打印机)`),
  new RegExp(`亮红灯|亮黄灯|红灯${SAME_CLAUSE}{0,3}(?:闪|亮)|指示灯|灯一直闪|错误代码|错误码|(?:显示|提示|弹出)${SAME_CLAUSE}{0,4}(?:故障|离线|脱机)`),
  new RegExp(`(?:屏幕|触摸屏|触屏)${SAME_CLAUSE}{0,6}(?:没反应|不动|点不了|点不动|黑了|黑屏|花了|碎了|裂了|失灵)`),
  // 有危险的征兆
  /(?<![到得])冒烟|着火|起火|冒火|烧焦|烧糊|焦糊|糊味|焦味|怪味|烧起来|漏电|触电|电到我|电了我|被电了|被电到|电了一下|异响|怪响|怪声|响声(?:很大|好大|特别大)|噼里啪啦|噼啪|嗡嗡|咔咔|哒哒|吱吱|滋滋/,
  // 想自己开盖、取纸盒，或者盖不回去
  new RegExp(`(?:打开|拆开|拆掉|拆下|掀开|拉开|抽出|取出|卸下|拆)${SAME_CLAUSE}{0,6}(?:前盖|后盖|盖板|盖子|纸盒|纸盘|纸仓|机身|外壳)`),
  new RegExp(`(?:前盖|后盖|盖板|盖子|纸盒|纸盘|纸仓)${SAME_CLAUSE}{0,8}(?:开|拆|取|抽|拉|装|关|合|盖不上)`),
  // 想自己重启、断电
  new RegExp(`(?:重启|重新启动|关掉|断电|拔电|插拔)${SAME_CLAUSE}{0,6}${DEVICE}`),
  new RegExp(`${DEVICE}${SAME_CLAUSE}{0,8}(?:重启|重新启动|断电|拔电)`),
  // 想自己开关机（「一体机几点关机」是在问服务时间，要带「怎么、能不能、帮我」才算）
  new RegExp(`${DEVICE}${SAME_CLAUSE}{0,4}${HOW_TO}${SAME_CLAUSE}{0,2}(?:开机|关机)|${HOW_TO}${SAME_CLAUSE}{0,4}${DEVICE}${SAME_CLAUSE}{0,4}(?:开机|关机)`),
  new RegExp(`电源键|电源开关|长按电源|按电源|(?<!选)拔(?:掉|下|了)?(?:电源|插头|电线|网线|线(?!上|下|路|索))|把(?:线|电源|插头)${SAME_CLAUSE}{0,2}拔|(?:电源|插头)${SAME_CLAUSE}{0,4}(?:拔|插拔)`),
  /重启(?:一下|试试|下|就好)|关了?(?:再|重)开|关掉重开/,
]

// 「修改」「拆分」这类词里的修、拆不算。
const REPAIR_VERB = '(?:拆开|拆掉|拆(?!分|迁|解)|修理|维修|修(?!改|订|饰|正|辞|养|读))'
/** 想自己修、自己拆。维修也是一个行当，所以这一类碰到求职的词就放过（见 JOB_WORDS）。 */
const REPAIR_PATTERNS: readonly RegExp[] = [
  new RegExp(`${REPAIR_VERB}${SAME_CLAUSE}{0,6}${DEVICE}`),
  new RegExp(`${DEVICE}${SAME_CLAUSE}{0,8}${REPAIR_VERB}`),
]

/**
 * 「打不出来」「打不了」单看分不清是打印还是打字、打电话，所以单列：
 * 后面要么没话了，要么接「来、了、怎么办」；「打不出亮点」「打不了交道」是别的意思。
 */
const CANNOT_PRINT_OUT = /打不(?:出|了)(?:东西|文件|纸)?(?:来|了|啊|呀|呢|吗|怎么|咋|$|[，,。！？!?、])/
const NOT_ABOUT_PRINTER = /字|拼音|键盘|输入法|姓|名字|姓名|电话|号码/

/** 在说求职内容：把这段经历写进简历、岗位要求里提到、面试官会问。 */
const ABOUT_JOB_CONTENT =
  /写进|写到|写在|写入|怎么写|如何写|怎么描述|怎么表述|怎么表达|润色|优化|改写|这句|这段|简历里|简历中|简历上|经历|经验|职责|工作内容|jd|招聘要求|任职要求|岗位要求|目标岗位|求职意向|应聘|岗位[:：]|职位[:：]|面试官|面试题|自我介绍|求职信|强项|擅长|熟悉|从事|做过|干过|工作过|我负责|负责过|工程师|技术员|操作工|维修工/
/** 维修这一行的求职话题里常见的词。只用来放过「修、拆」那一类，不用来放过故障征兆。 */
const JOB_WORDS = /工作|岗位|职位|面试|求职|招聘|简历|专业|证书|技能|培训|工资|薪资|行业|学徒/
/**
 * 明说了是眼前这台机器。有这些词时，即使提到了简历、经历也照样算故障。
 * 「刚才」「刚刚」不算：「刚才面试官问我卡纸怎么处理」说的是面试，不是这台机器。
 */
const HERE_AND_NOW = /这台|这个机器|这机器|本机|正在打|正在印|打到一半|印到一半/

/**
 * 刚收到固定回答后追问能不能自己动手、谁来修（「那我自己能弄吗」「教我怎么取」「什么时候有人来修」）：
 * 照样不送模型。只认动手修、等人修的说法——「自己写的简历」「怎么修改」「辅修了法学」「教我怎么处理人际关系」
 * 是换了话题，要放回给模型，不能把人困在固定回答里。
 */
const FOLLOW_UP = new RegExp(
  `自己(?:能|可以|来|去)?(?:弄|修(?!改)|处理|动手|取|拿|拆|解决|搞)|我(?:来|能|会|可以)(?:弄|修(?!改)|取|拿|拆|试试)` +
  `|教我(?:怎么)?(?:弄|取|拿|修(?!改)|拆|开(?!头|始|场))|(?:怎么|咋|如何)(?:弄|取出|拿出|抽出|拽出|拉出|修(?!改|订|饰|正)|拆(?!分))` +
  `|(?:什么时候|啥时候|多久|谁|有人|找人|叫人|派人)${SAME_CLAUSE}{0,4}(?:修|处理|弄好)|修好|修一下|${TAKE_OUT}出来` +
  `|(?:拍|踢|敲|砸|晃|摇)(?:一|两|几)?(?:下|脚|拍)|按(?:哪|了|一下)?${SAME_CLAUSE}{0,4}键`,
)
const MAX_FOLLOW_UP_CHARS = 40

function userSentence(message: string): string {
  return message.replace(TOPIC_PREFIX, '').replace(/\s+/g, '').toLowerCase()
}

/**
 * 这句话是不是在求助设备故障。
 * @param justAnsweredFault 同一会话的上一轮是否刚回过固定回答
 */
export function isDeviceFaultQuestion(message: string, justAnsweredFault = false): boolean {
  const text = userSentence(message)
  if (!text || text.length > MAX_FAULT_QUESTION_CHARS) return false
  const hereAndNow = HERE_AND_NOW.test(text)
  if (ABOUT_JOB_CONTENT.test(text) && !hereAndNow) return false
  if (SYMPTOM_PATTERNS.some((pattern) => pattern.test(text))) return true
  if (CANNOT_PRINT_OUT.test(text) && !NOT_ABOUT_PRINTER.test(text)) return true
  if (REPAIR_PATTERNS.some((pattern) => pattern.test(text)) && (hereAndNow || !JOB_WORDS.test(text))) return true
  return justAnsweredFault && text.length <= MAX_FOLLOW_UP_CHARS && FOLLOW_UP.test(text)
}
